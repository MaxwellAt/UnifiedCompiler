use serde::{Deserialize, Serialize};
use std::collections::HashMap;
use std::fs;
use std::path::{Path, PathBuf};

#[derive(Debug, Clone, Serialize, Deserialize, Default)]
pub struct UnicompConfig {
    pub host: Option<HostConfig>,
    pub sync: Option<SyncConfig>,
    pub env: Option<HashMap<String, String>>,
}

#[derive(Debug, Clone, Serialize, Deserialize, Default)]
pub struct HostConfig {
    pub default: Option<String>,
    pub timeout_seconds: Option<u64>,
}

#[derive(Debug, Clone, Serialize, Deserialize, Default)]
pub struct SyncConfig {
    pub ignore: Option<Vec<String>>,
    pub artifacts: Option<Vec<String>>,
}

impl UnicompConfig {
    /// Discovers `.unicomp.toml` starting from the current directory and walking up to parent directories.
    pub fn find_and_load(start_dir: &Path) -> Option<(Self, PathBuf)> {
        let mut curr = start_dir.to_path_buf();
        loop {
            let candidate = curr.join(".unicomp.toml");
            if candidate.is_file() {
                if let Ok(content) = fs::read_to_string(&candidate) {
                    if let Ok(config) = toml::from_str::<UnicompConfig>(&content) {
                        return Some((config, candidate));
                    }
                }
            }

            if !curr.pop() {
                break;
            }
        }

        // Global fallback: ~/.unicomp/config.toml
        if let Ok(home) = std::env::var("USERPROFILE").or_else(|_| std::env::var("HOME")) {
            let global_path = PathBuf::from(home).join(".unicomp").join("config.toml");
            if global_path.is_file() {
                if let Ok(content) = fs::read_to_string(&global_path) {
                    if let Ok(config) = toml::from_str::<UnicompConfig>(&content) {
                        return Some((config, global_path));
                    }
                }
            }
        }

        None
    }

    /// Generates a starter `.unicomp.toml` file with helpful comments.
    pub fn default_template() -> &'static str {
        r#"# UniComp Project Configuration (.unicomp.toml)
# Defines the default execution host, synchronization rules, and environment variables.

[host]
# Default host address and port (e.g. your cluster node, desktop, or server IP)
default = "127.0.0.1:9876"

# Execution timeout in seconds (default: 300)
timeout_seconds = 300

[sync]
# Patterns to ignore during workspace synchronization (in addition to .gitignore)
ignore = [
    "datasets/",
    "*.tmp",
    "*.log"
]

# Patterns of artifacts generated by the remote host to sync back to local disk
artifacts = [
    "output/",
    "models/*.pt"
]

[env]
# Environment variables to inject into the remote execution environment
# RUST_LOG = "info"
# PYTHONUNBUFFERED = "1"
"#
    }
}
